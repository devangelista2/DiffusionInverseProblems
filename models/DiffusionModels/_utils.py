import math

import torch
from torch import nn


# ----------------------------------------
# Change model to single - half precision
# ----------------------------------------
def convert_module_to_f16(l):
    """
    Convert primitive modules to float16.
    """
    if isinstance(l, (nn.Conv1d, nn.Conv2d, nn.Conv3d)):
        l.weight.data = l.weight.data.half()
        if l.bias is not None:
            l.bias.data = l.bias.data.half()


def convert_module_to_f32(l):
    """
    Convert primitive modules to float32, undoing convert_module_to_f16().
    """
    if isinstance(l, (nn.Conv1d, nn.Conv2d, nn.Conv3d)):
        l.weight.data = l.weight.data.float()
        if l.bias is not None:
            l.bias.data = l.bias.data.float()


# ----------------------------------------
# Utilities specific for Diffusion Models
# ----------------------------------------
def get_timestep_embedding(timesteps, embedding_dim, max_period=10000):
    """
    Build sinusoidal embeddings.
    This matches the implementation in tensor2tensor, but differs slightly
    from the description in Section 3.5 of "Attention Is All You Need".
    """

    half_dim = embedding_dim // 2
    emb = math.log(max_period) / (half_dim - 1)
    emb = torch.exp(torch.arange(half_dim, dtype=torch.float32) * -emb)
    emb = emb.to(device=timesteps.device)
    emb = timesteps.float()[:, None] * emb[None, :]
    emb = torch.cat([torch.sin(emb), torch.cos(emb)], dim=1)
    if embedding_dim % 2 == 1:  # zero pad
        emb = torch.nn.functional.pad(emb, (0, 1, 0, 0))
    return emb


def sinusoidal_embedding(t, embedding_dim):
    embedding_min_frequency = 1.0
    embedding_max_frequency = 10_000
    frequencies = torch.exp(
        torch.linspace(
            math.log(embedding_min_frequency),
            math.log(embedding_max_frequency),
            embedding_dim // 2,
        )
    ).to(t.device)
    angular_speeds = 2.0 * math.pi * frequencies
    emb = t.float() * angular_speeds[None, :, None, None]
    embeddings = torch.cat([torch.sin(emb), torch.cos(emb)], dim=1)
    return embeddings

def update_ema(target_params, source_params, rate=0.99):
    """
    Update target parameters to be closer to those of source parameters using
    an exponential moving average.

    :param target_params: the target parameter sequence.
    :param source_params: the source parameter sequence.
    :param rate: the EMA rate (closer to 1 means slower).
    """
    for targ, src in zip(target_params, source_params):
        targ.detach().mul_(rate).add_(src, alpha=1 - rate)


